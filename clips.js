// וגם כגיבוי – אם הקלטה חסרה, הטקסט נקרא בקול של הטלפון.
(function () {
  const ONES = ['', 'אחת', 'שתיים', 'שלוש', 'ארבע', 'חמש', 'שש', 'שבע', 'שמונה', 'תשע'];
  const TENS = ['', 'עשר', 'עשרים', 'שלושים', 'ארבעים', 'חמישים', 'שישים', 'שבעים', 'שמונים', 'תשעים'];
  function heb(n) {
    if (n < 10) return ONES[n];
    if (n === 10) return 'עשר';
    if (n < 20) return (n === 12 ? 'שתים' : ONES[n - 10]) + ' עשרה';
    if (n < 100) { const t = TENS[Math.floor(n / 10)], o = n % 10; return o ? t + ' ו' + ONES[o] : t; }
    return String(n);
  }
  const minW = m => m === 1 ? 'דקה' : m === 2 ? 'שתי דקות' : heb(m) + ' דקות';

  const C = {
    now_run: 'עכשיו ריצה,',
    run_of: 'כעת ריצה של',
    now_walk: 'עכשיו הליכה,',
    cd5: 'מתחילים בעוד חמש שניות.', cd10: 'מתחילים בעוד עשר שניות.', cd15: 'מתחילים בעוד חמש עשרה שניות.',
    cd20: 'מתחילים בעוד עשרים שניות.', cd30: 'מתחילים בעוד שלושים שניות.',
    n1: 'אחת', n2: 'שתיים', n3: 'שלוש',
    go: 'יוצאים!',
    plus30: 'הוספנו חצי דקה.',
    last_min: 'דקה אחרונה!',
    warm: 'מתחילים בחימום,',
    cool: 'כל הכבוד! עכשיו שחרור,',
    walkw: 'הליכה.',
    last_seg: 'זה הקטע האחרון.',
    r1: 'סיבוב ראשון',
    rlast: 'סיבוב אחרון!',
    half: 'חצי עבר.',
    one_min: 'עוד דקה.',
    pause: 'הפסקה.',
    resume: 'ממשיכים!',
    done: 'סיימת! כל הכבוד!',
    ran: 'רצת',
    test: 'שלום! ככה אני אשמע בזמן הריצה.',
    s15: 'חמש עשרה שניות.', s30: 'שלושים שניות.', s45: 'ארבעים וחמש שניות.',
    and_s15: 'וחמש עשרה שניות.', and_s30: 'ושלושים שניות.', and_s45: 'וארבעים וחמש שניות.',
    cheer1: 'ממשיכים חזק, זה נראה מעולה!',
    cheer2: 'עברנו כבר יותר מחצי אימון!',
    cheer3: 'נשימה עמוקה, כתפיים רפויות.',
    cheer4: 'קצב יפה, ממשיכים ככה!',
    cheer5: 'כל צעד נחשב!',
    cheer6: 'הגוף חזק יותר ממה שנדמה.',
    cheer7: 'עוד קצת, ואפשר להתגאות!',
    cheer_last: 'זה הסיבוב האחרון, נותנים הכל!',
    record: 'ויש לנו שיא חדש!',
    prog_done: 'אימון נוסף בתוכנית הושלם.',
  };
  for (let m = 1; m <= 90; m++) C['m' + m] = (m === 1 ? 'דקה אחת' : minW(m)) + '.';
  for (let m = 1; m <= 30; m++) C['m' + m + 'h'] = minW(m) + ' וחצי.';
  for (let n = 2; n <= 40; n++) { C['r' + n] = 'סיבוב ' + heb(n); C['of' + n] = 'מתוך ' + heb(n) + '.'; }

  const api = { CLIPS: C, heb };
  if (typeof module !== 'undefined') module.exports = api; else window.RW_CLIPS = api;
})();
